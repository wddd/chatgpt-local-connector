import { createHash } from 'node:crypto';
import { readFile, readdir, mkdir, rm, copyFile, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';

export const inputKey = inputs => createHash('sha256').update(JSON.stringify(inputs)).digest('hex');

export function dependenciesMatch(receipt, inputs) {
  return receipt?.schema === 1 && receipt.key === inputKey(inputs);
}

export async function installDependencies(root, install) {
  const inputs = { lock: inputKey(await readFile(path.join(root, 'package-lock.json'), 'utf8')),
    manifest: inputKey(await readFile(path.join(root, 'package.json'), 'utf8')),
    node: process.version, npm: (await import('node:child_process')).execFileSync(process.platform === 'win32' ? 'cmd.exe' : 'npm',
      process.platform === 'win32' ? ['/d', '/s', '/c', 'npm --version'] : ['--version'], { encoding: 'utf8' }).trim(), platform: process.platform, arch: process.arch };
  const marker = path.join(root, 'node_modules/.arc-dependencies.json');
  let receipt;
  try { receipt = JSON.parse(await readFile(marker)); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  // npm creates this only after a complete installation; removing node_modules invalidates the pass.
  let installed = false;
  try { installed = (await stat(path.join(root, 'node_modules/.package-lock.json'))).isFile(); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (installed && dependenciesMatch(receipt, inputs)) { console.log('Dependencies unchanged; npm ci skipped.'); return; }
  await rm(marker, { force: true });
  await install();
  await writeFile(marker, JSON.stringify({ schema: 1, key: inputKey(inputs), inputs }) + '\n');
}

// Keep Cargo's watched assets stable when the generated bytes did not change.
export async function syncDirectory(source, destination) {
  await mkdir(destination, { recursive: true });
  const entries = await readdir(source, { withFileTypes: true });
  const names = new Set(entries.map(entry => entry.name));
  for (const name of await readdir(destination)) if (!names.has(name)) await rm(path.join(destination, name), { recursive: true, force: true });
  for (const entry of entries) {
    const from = path.join(source, entry.name), to = path.join(destination, entry.name);
    if (entry.isDirectory()) await syncDirectory(from, to);
    else {
      const bytes = await readFile(from);
      let previous;
      try { previous = await readFile(to); } catch (error) { if (error.code !== 'ENOENT') throw error; }
      if (!previous?.equals(bytes)) await copyFile(from, to);
    }
  }
}
